#!/usr/bin/env python3
"""Packs ui/index.html into web_ui.h (gzipped byte array) for the firmware.

Run after editing index.html:   python3 ui/build_ui.py
"""
import gzip, pathlib

here = pathlib.Path(__file__).resolve().parent
html = (here / "index.html").read_text(encoding="utf-8")
# light minify: drop indentation and blank lines (keeps the code readable in index.html)
html = "\n".join(line.strip() for line in html.splitlines() if line.strip())
data = gzip.compress(html.encode("utf-8"), compresslevel=9, mtime=0)

rows = []
for i in range(0, len(data), 20):
    rows.append("  " + ",".join(f"0x{b:02x}" for b in data[i:i + 20]))
body = ",\n".join(rows)
out = f"""// AUTO-GENERATED by ui/build_ui.py from ui/index.html - do not edit by hand.
#pragma once
#include <Arduino.h>
const size_t WEB_UI_GZ_LEN = {len(data)};
const uint8_t WEB_UI_GZ[] PROGMEM = {{
{body}
}};
"""
(here.parent / "web_ui.h").write_text(out)
print(f"web_ui.h written: {len(html)} bytes HTML -> {len(data)} bytes gzipped")
