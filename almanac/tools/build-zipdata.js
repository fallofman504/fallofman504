// Builds data/zipdata.js from two public sources:
//   1. USDA Plant Hardiness Zone Map 2023, ZIP edition (PRISM Climate Group, Oregon State Univ.)
//      phzm_us_zipcode_2023.csv  (columns: zipcode,zone,trange,zonetitle)
//   2. ZIP code place names from the `zipcodes` npm package (lib/codes.js)
// Usage: node build-zipdata.js <phzm_us_zipcode_2023.csv> <zipcodes/lib/codes.js> <out.js>
const fs = require('fs');
const [csvPath, codesPath, outPath] = process.argv.slice(2);

const ZONES = ['1a','1b','2a','2b','3a','3b','4a','4b','5a','5b','6a','6b','7a','7b',
  '8a','8b','9a','9b','10a','10b','11a','11b','12a','12b','13a','13b'];

// codes.js is "exports.codes = {...};\nexports.stateMap = ..." -- parse the JSON, don't execute it.
const src = fs.readFileSync(codesPath, 'utf8');
const start = src.indexOf('{');
const end = src.indexOf('exports.stateMap');
const places = JSON.parse(src.slice(start, end).trim().replace(/;$/, ''));

const states = [];
const rows = [];
for (const line of fs.readFileSync(csvPath, 'utf8').trim().split('\n').slice(1)) {
  const [zip, zone] = line.split(',');
  const zi = ZONES.indexOf(zone);
  if (zi < 0 || !/^\d{5}$/.test(zip)) continue;
  const p = places[zip];
  let si = -1, city = '';
  if (p && p.state) {
    si = states.indexOf(p.state);
    if (si < 0) { states.push(p.state); si = states.length - 1; }
    city = (p.city || '').replace(/[|;]/g, ' ');
  }
  rows.push([zip, zi, si, city]);
}
rows.sort((a, b) => a[0].localeCompare(b[0]));

// Record format: zip(5) zone(1 letter a-z) state(base36 2 chars or "--") city ; next...
const rec = rows.map(([zip, zi, si, city]) =>
  zip + String.fromCharCode(97 + zi) + (si < 0 ? '--' : si.toString(36).padStart(2, '0')) + city).join(';');

const out = `// Generated by tools/build-zipdata.js -- do not edit by hand.
// Sources: USDA Plant Hardiness Zone Map 2023 (PRISM Climate Group, Oregon State University);
// place names from the "zipcodes" npm package.
window.ZIPDATA = {zones:${JSON.stringify(ZONES)},states:${JSON.stringify(states)},rec:${JSON.stringify(rec)}};
`;
fs.writeFileSync(outPath, out);
console.log(rows.length, 'zips;', rows.filter(r => r[2] < 0).length, 'without place name;', (out.length / 1024).toFixed(0) + ' KB');
